app.post('/api/forms/:type', rateLimit, async (req, res) => {
  const def = FORMS[req.params.type]
  if (!def) return res.status(404).json({ error: 'Unknown form' })

  const tag = `[forms/${req.params.type}]`

  // Honeypot: real users never see or fill this field.
  if (req.body?.website) {
    console.warn(`${tag} honeypot filled — submission dropped`)
    return res.json({ ok: true })
  }
  const elapsed = Number(req.body?.elapsedMs)
  if (Number.isFinite(elapsed) && elapsed < MIN_FILL_MS) {
    console.warn(`${tag} submitted ${elapsed}ms after load — submission dropped`)
    return res.json({ ok: true })
  }

  const fields = validateLead(req.params.type, req.body)
  if (Object.keys(fields).length) {
    return res.status(400).json({ error: 'Please fix the highlighted fields and try again.', fields })
  }

  const data = clean(req.body, def)
  const key = fingerprint(req.params.type, data)
  if (recentLeads.has(key)) {
    console.log(`${tag} duplicate submission ignored`)
    return res.json({ ok: true })
  }

  const lead = {
    form: req.params.type,
    submittedAt: new Date().toISOString(),
    data,
    attribution: cleanAttribution(req.body?.attribution),
    consent: 'consent' in LEAD_FORMS[req.params.type] ? req.body.consent === true : undefined,
  }
  const { text, html } = buildEmail(def, lead)

  // Deliver to every configured destination. The lead counts as received if
  // at least one succeeded; partial failures are logged for follow-up.
  const deliveries = [
    transporter
      .sendMail({
        from: `"Teemly Website" <${SMTP_USER}>`,
        to: def.mailTo,
        replyTo: data.email,
        subject: def.subject(data).replace(/[\r\n]+/g, ' '),
        text,
        html,
      })
      .then(() => console.log(`${tag} lead emailed to ${def.mailTo}`)),
  ]
  if (LEAD_WEBHOOK_URL) deliveries.push(postToWebhook(lead).then(() => console.log(`${tag} lead sent to webhook`)))

  const results = await Promise.allSettled(deliveries)
  const failed = results.filter((r) => r.status === 'rejected')
  for (const r of failed) console.error(`${tag} delivery failed:`, r.reason)
  if (failed.length === results.length) {
    return res.status(502).json({
      error: 'Sorry, we could not send your request just now. Please try again in a moment — your details are still in the form.',
    })
  }
  recentLeads.set(key, Date.now())

  // The lead reached us, so the submission is a success regardless of the
  // auto-reply. Send the confirmation in the background and only log failures.
  res.json({ ok: true })

  const reply = buildAutoReply(def, data)
  transporter
    .sendMail({
      from: `"Teemly" <${SMTP_USER}>`,
      to: data.email,
      replyTo: def.mailTo,
      subject: reply.subject,
      text: reply.text,
      html: reply.html,
      attachments: LOGO_ATTACHMENT ? [LOGO_ATTACHMENT] : [],
    })
    .then(() => console.log(`${tag} auto-reply sent to ${data.email}`))
    .catch((err) => console.error(`${tag} auto-reply to submitter failed:`, err.message))
})

// ---- Site sign-in (product tour and chat assistant): records the visitor
// and tells the team. The tour and the chat answers ship with the site, so
// this unlocks them in the browser rather than guarding a secret; what
// matters here is capturing the lead.
const TOUR_DEF = {
  title: 'Website sign-in',
  fields: { name: 'Name', email: 'Work email', company: 'Company', role: 'Role', companySize: 'Company size', country: 'Country' },
}
const SIGNIN_SOURCES = { tour: 'Product tour', chatbot: 'Chat assistant' }

app.post('/api/tour/unlock', rateLimit, async (req, res) => {
  const tag = '[tour]'
  if (req.body?.website) {
    console.warn(`${tag} honeypot filled — sign-in not recorded`)
    return res.json({ ok: true })
  }
  const elapsed = Number(req.body?.elapsedMs)
  if (Number.isFinite(elapsed) && elapsed < MIN_FILL_MS) {
    console.warn(`${tag} submitted ${elapsed}ms after load — sign-in not recorded`)
    return res.json({ ok: true })
  }

  // the chat assistant asks only for a name and email; the tour for the full form
  const form = req.body?.form === 'chat' ? 'chat' : 'tour'
  const fields = validateLead(form, req.body)
  if (Object.keys(fields).length) {
    return res.status(400).json({ error: 'Please fix the highlighted fields and try again.', fields })
  }

  const data = clean(req.body, TOUR_DEF)
  data.email = data.email.toLowerCase()
  const attribution = cleanAttribution(req.body?.attribution)
  const source = SIGNIN_SOURCES[req.body?.source] ? req.body.source : 'tour'
  // the question a chat visitor asked before signing in
  const question = typeof req.body?.question === 'string' ? req.body.question.replace(/[\u0000-\u001f\u007f]/g, ' ').trim().slice(0, 300) : ''
  try {
    const result = await query(
      `INSERT INTO tour_signups (email, name, company, role, company_size, country, consent, attribution, source, first_question)
       VALUES (?, ?, ?, ?, ?, ?, 1, ?, ?, ?)
       ON DUPLICATE KEY UPDATE visits = visits + 1, last_seen_at = CURRENT_TIMESTAMP(3)`,
      [data.email, data.name, data.company, data.role, data.companySize, data.country, JSON.stringify(attribution), source, question],
    )
    // affectedRows is 1 for a new row, 2 when an existing email was updated
    if (result.affectedRows !== 1) return res.json({ ok: true })
  } catch (err) {
    console.error(`${tag} could not save sign-in:`, err.message)
    return res.status(502).json({ error: 'Sorry, we could not unlock the tour just now. Please try again in a moment.' })
  }
  res.json({ ok: true })

  const lead = {
    form: source,
    submittedAt: new Date().toISOString(),
    data: { ...data, source: SIGNIN_SOURCES[source], question: question || '-' },
    attribution,
    consent: true,
  }
  const def = { ...TOUR_DEF, fields: { ...TOUR_DEF.fields, source: 'Signed in from', question: 'Question asked' } }
  const { text, html } = buildEmail(def, lead)
  const to = process.env.MAIL_TO_TOUR || MAIL_TO
  transporter
    .sendMail({
      from: `"Teemly Website" <${SMTP_USER}>`,
      to,
      replyTo: data.email,
      subject: `New sign-in (${SIGNIN_SOURCES[source]}) — ${data.name}${data.company ? ` (${data.company})` : ''}`.replace(/[\r\n]+/g, ' '),
      text,
      html,
    })
    .then(() => console.log(`${tag} sign-in emailed to ${to}`))
    .catch((err) => console.error(`${tag} notification failed:`, err.message))
  if (LEAD_WEBHOOK_URL) postToWebhook(lead).catch((err) => console.error(`${tag} webhook failed:`, err.message))
})

// ---- Serve the built site with SPA fallback ----
const DIST = path.join(ROOT, 'dist')
app.use(express.static(DIST))
app.use((req, res, next) => {
  if (req.method !== 'GET' || req.path.startsWith('/api/') || req.path.startsWith('/uploads/')) return next()
  res.sendFile(path.join(DIST, 'index.html'))
})

try {
  await dbReady
} catch (err) {
  console.error(`Could not connect to MySQL (${err.code || err.message}). Check MYSQL_HOST, MYSQL_USER, MYSQL_PASSWORD and MYSQL_DATABASE in .env.`)
  process.exit(1)
}

app.listen(PORT, () => {
  console.log(`Teemly server listening on http://localhost:${PORT}`)
})
